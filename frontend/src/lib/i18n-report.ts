// labels: directions, strengths, designs, risk of bias). Components read a pair with `L(lang, RC.x.y)`
// (components/review/text.ts); a pair with `{slot}` placeholders takes React nodes through `fill`. No Thai or English
// copy is written inline in the report components (lib/i18n-report.test.ts scans them), so a Thai report reads all
// Thai and an English one all English. Data (titles, card fields, model text) is never translated here.
