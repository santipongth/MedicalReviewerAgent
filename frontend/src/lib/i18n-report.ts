/** Each language named in its own script (the report-language switch, the title block's language). */
export const LANGUAGE_NAME: Record<Lang, string> = { th: "ภาษาไทย", en: "English" };

/** Thai copy that is the same in both languages: abbreviations, symbols and proper nouns. */
export const SHARED_TH = new Set(["RCT", "PICO", "PCC", "AUC", "SR/MA", "HTML", "Markdown", "CSV", "JSON", "k", "n", "–", "·"]);

/**
 * The language of a data field shown in a report of `lang`, when it differs (Plan 20 Task 7): a Thai report can carry
 * English card fields the engine did not translate, and an English view of a Thai report can carry Thai ones. The block
 * is marked with its own `lang` so a screen reader switches voice; the text itself is never machine-translated here.
 */
export function fieldLang(text: string | null | undefined, lang: Lang): Lang | undefined {
  if (!text) return undefined;
  if (lang === "th") return !hasThai(text) && /[A-Za-z]{2}/.test(text) ? "en" : undefined;
  return hasThai(text) ? "th" : undefined;
}

